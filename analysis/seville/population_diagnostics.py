def _save(fig, out, manifest, filename, title, note=""):
    fig.tight_layout()
    fig.savefig(out / (filename + ".png"), dpi=165, bbox_inches="tight", facecolor="white")
    plt.close(fig)
    manifest.append({"file": filename + ".png", "title": title, "note": note})


def _age_group_bars(table, out, manifest, filename, title, min_eff, xlabel="Age group", ylabel="Share (%)"):
    """Grouped age-band bars for Census and Final; preserve established filenames."""
    if table.empty:
        return
    ages = sorted(table.age_start.dropna().unique())
    if not ages:
        return
    sources = list(table.source.dropna().unique())
    if not sources:
        return
    x = np.arange(len(ages))
    width = min(0.36, 0.84 / len(sources))
    fig, ax = plt.subplots(figsize=(max(10, len(ages) * 0.72), 5.4))
    for i, name in enumerate(sources):
        sub = table.loc[table.source.eq(name)].set_index("age_start").reindex(ages)
        values = pd.to_numeric(sub.rate_pct, errors="coerce")
        n_eff = pd.to_numeric(
            sub["n_eff"] if "n_eff" in sub else sub.get("effective_n", pd.Series(index=sub.index, dtype=float)),
            errors="coerce",
        )
        if name == "HTS":
            values = values.where(n_eff >= min_eff)
        pos = x + (i - (len(sources) - 1) / 2) * width
        ax.bar(pos, values, width=width, label=name,
               color=COLORS.get(name, "#888"), zorder=3)
        if name == "HTS" and ylabel.endswith("(%)"):
            # Descriptive intervals, only for survey cells meeting the threshold.
            interval = 1.96 * 100 * np.sqrt(
                (values / 100).clip(0, 1) * (1 - (values / 100).clip(0, 1)) /
                n_eff.replace(0, np.nan))
            interval = np.minimum(interval, values)
            upper = np.minimum(1.96 * 100 * np.sqrt(
                (values / 100).clip(0, 1) * (1 - (values / 100).clip(0, 1)) /
                n_eff.replace(0, np.nan)), 100 - values)
            ax.errorbar(pos, values, yerr=np.vstack([interval, upper]),
                        fmt="none", ecolor=COLORS.get(name, "#888"),
                        elinewidth=1, capsize=2, zorder=4)
    ax.set_xticks(x, [str(int(age)) + ("+" if age == ages[-1] else "") for age in ages],
                  rotation=45, ha="right")
    ax.set(xlabel=xlabel, ylabel=ylabel, title=title)
    if ylabel.endswith("(%)"):
        ax.set_ylim(0, 100)
    else:
        ax.set_ylim(bottom=0)
    ax.grid(alpha=0.2, axis="y", zorder=0)
    ax.set_axisbelow(True)
    ax.legend(frameon=False)
    _save(fig, out, manifest, filename, title,
          "Grouped age bands; only Final and Census series are generated by this validation stage.")

def _bars(data, col, out, manifest, filename, title, percentage=True, preferred=None):
    data = {name: s.dropna() for name, s in data.items() if len(s.dropna())}
    if not data:
        return
    cats = preferred or sorted(set().union(*(s.index for s in data.values())))
    fig, ax = plt.subplots(figsize=(max(9, .6 * len(cats) + 3), 5))
    width = .8 / len(data)
    for i, (name, series) in enumerate(data.items()):
        s = series.reindex(cats, fill_value=0)
        if percentage and s.sum() > 0:
            s = 100 * s / s.sum()
        ax.bar(np.arange(len(cats)) + (i - (len(data)-1)/2)*width,
               s.values, width=width, label=name, color=COLORS.get(name, "#888"))
    ax.set_xticks(np.arange(len(cats)), [str(c) for c in cats], rotation=45, ha="right")
    ax.set_title(title); ax.set_ylabel(col); ax.grid(axis="y", alpha=.2); ax.legend(frameon=False)
    _save(fig, out, manifest, filename, title)


def _distribution(df, column):
    d = df.loc[df[column].notna()]
    return d.groupby(column, observed=True)["_w"].sum()


def _age_mix(pop, sources, out, manifest):
    df = pop.copy()
    df["age_start"] = numeric(df.age_class)
    df["_w"] = check_weight(df, "weight", "census population")
    dist = {"Census": _distribution(df, "age_start")}
    for name, p in sources.items():
        d = p.copy()
        d["age_start"] = (np.floor(d.age / 5) * 5).clip(upper=100)
        dist[name] = _distribution(d, "age_start")
    _bars(dist, "Population share (%)", out, manifest, "01_age_share", "Age distribution, 5-year groups")
    rows = []
    for name, s in dist.items():
        for key, val in (100*s/s.sum()).items():
            rows.append({"source": name, "age_start": key, "population_share_pct": val})
    pd.DataFrame(rows).to_csv(out/"age_share.csv", index=False)
    sex_d = {"Census": pop.assign(_w=check_weight(pop, "weight", "census population"),
                                   sex_norm=sex(pop.sex))}
    sex_d.update(sources)
    _bars({k: _distribution(p, "sex_norm") for k,p in sex_d.items()}, "Population share (%)",
          out, manifest, "02_sex_share", "Population by sex")
    rows = []
    for name, p in sex_d.items():
        s = _distribution(p, "sex_norm"); total=s.sum()
        for k,v in s.items():
            rows.append({"source":name, "sex":k, "share_pct":100*v/total})
    pd.DataFrame(rows).to_csv(out/"sex_share.csv",index=False)


def _rate_metric(pop, ref, sources, metric, breaks, min_age, out, manifest, prefix, title, min_eff):
    tables = []
    if ref is not None:
        for by_sex in (False, True):
            census = census_outcome_rates(pop, ref, breaks, by_sex=by_sex)
            census["source"] = "Census"; census["by_sex"] = by_sex
            tables.append(census)
    for name,p in sources.items():
        for by_sex in (False, True):
            result = rate_groups(p, breaks, metric, group_sex=by_sex, min_age=min_age)
            result["source"] = name; result["by_sex"] = by_sex
            tables.append(result)
    if not tables:
        return pd.DataFrame()
    table = pd.concat(tables, ignore_index=True)
    table = table.loc[table.age_start.ge(min_age)].copy()
    table["minimum_effective_n"] = min_eff
    table["masked_for_plot"] = table.source.eq("HTS") & table.n_eff.lt(min_eff)
    table.to_csv(out/(prefix+"_by_age_sex.csv"), index=False)
    _age_group_bars(table.loc[~table.by_sex], out, manifest, prefix+"_age", title, min_eff)
    for sx in ("male", "female"):
        sub = table.loc[table.by_sex & table.sex.eq(sx)]
        _age_group_bars(sub, out, manifest, prefix+"_"+sx, title+" — "+sx, min_eff)
    # Sex x age residual heat map, Final vs Census only.
    if ref is not None and "Final" in sources:
        pivot = table.loc[table.by_sex & table.source.isin(["Final", "Census"])].pivot_table(
            index=["sex", "age_start"], columns="source", values="rate_pct", observed=True)
        if {"Census", "Final"}.issubset(pivot):
            gap = (pivot["Final"]-pivot["Census"]).unstack("sex")
            if not gap.empty:
                fig,ax=plt.subplots(figsize=(8.5, max(4, .42*len(gap))))
                image=ax.imshow(gap.to_numpy(dtype=float), aspect="auto", cmap="RdBu_r", vmin=-30, vmax=30)
                ax.set_xticks(range(len(gap.columns)),gap.columns)
                ax.set_yticks(range(len(gap.index)), [str(int(i)) for i in gap.index])
                ax.set_title("Final − Census " + title.lower() + " (percentage points)")
                fig.colorbar(image, ax=ax, label="Difference (pp)")
                _save(fig,out,manifest,prefix+"_gap_heatmap", "Final − Census: "+title,
                      "Census age cells are reconstructed using 5-year population splits.")
    return table


def _households(census_hh, sources, hts_hh, out, manifest):
    fields = ["households_1_person","households_2_persons","households_3_persons",
              "households_4_persons","households_5plus_persons"]
    if not set(fields).issubset(census_hh.columns):
        raise ValueError("Census households missing size columns")
    dist = {"Census": pd.Series({str(i if i < 5 else "5+"):float(numeric(census_hh[f]).sum())
                                 for i, f in enumerate(fields, 1)})}
    hh_total = float(numeric(census_hh.total_households).sum())
    rows = [{"source": "Census", "households_expanded": hh_total}]
    for name, persons in sources.items():
        if "household_id" not in persons:
            continue
        hh_sizes = persons.groupby("household_id", observed=True).size().clip(upper=5)
        dist[name] = hh_sizes.value_counts().sort_index().rename(index={5:"5+"})
        dist[name].index = dist[name].index.astype(str)
        rows.append({"source":name,"households_expanded":len(hh_sizes)*float(persons._w.iloc[0]) if len(persons) else 0})
    if hts_hh is not None and {"household_size", "household_weight"}.issubset(hts_hh):
        h = hts_hh.copy()
        h["size"] = numeric(h.household_size).clip(upper=5)
        h["size"] = h["size"].map(lambda k: str(int(k)) if pd.notna(k) and k < 5 else ("5+" if pd.notna(k) else pd.NA))
        h["_w"] = check_weight(h, "household_weight", "HTS households")
        dist["HTS"] = _distribution(h,"size")
    _bars(dist, "Share of households (%)", out, manifest,"06_household_size", "Household-size distribution",
          preferred=["1","2","3","4","5+"])
    table = pd.DataFrame({k: (s/s.sum()*100 if s.sum()>0 else s) for k,s in dist.items()}).fillna(0).reset_index().rename(columns={"index":"size"})
    table.to_csv(out/"household_size_share.csv",index=False)
    pd.DataFrame(rows).to_csv(out/"household_count_totals.csv",index=False)
    # Absolute household totals compare Census vs Final only.
    _bars({r["source"]:pd.Series([r["households_expanded"]], index=["all households"])
           for r in rows}, "Expanded households",out,manifest,"07_household_count", "Household totals (Final vs Census)",False)


def _whole_population_rates(census_pop, census_employment, census_licenses,
                            sources, out, manifest):
    """Employment and licence shares use ALL residents, including children.

    Age-specific plots retain age-group denominators, but this plot and the
    spatial maps divide by the full residential population, not 16+/18+.
    """
    census_total = float(check_weight(census_pop,"weight","census population").sum())
    references = {"employed_n":census_employment, "license_n":census_licenses}
    for metric,ref in references.items():
        num = float(check_weight(ref,"weight", "census outcome").sum())
        rows=[{"source":"Census", "metric":metric, "number_with_attribute":num,
               "total_residents":census_total,
               "share_pct":100*num/census_total if census_total else np.nan}]
        for name, group in sources.items():
            numerator = float((group[metric].fillna(0)*group._w).sum())
            denom = float(group._w.sum())
            rows.append({"source":name,"metric":metric,
                         "number_with_attribute":numerator,
                         "total_residents":denom,
                         "share_pct":100*numerator/denom if denom else np.nan})
        result=pd.DataFrame(rows)
        filename=("03_employment" if metric=="employed_n" else "04_license")+"_all_residents"
        result.to_csv(out/(filename+".csv"),index=False)
        data=result.set_index("source").share_pct
        _bars({name:pd.Series({"all residents":value}) for name,value in data.items()},
              "Share of all residents (%)",out,manifest,filename,
              ("Employed residents" if metric=="employed_n" else "Driving-licence holders")+
              " / all residents (including children)",percentage=False)



def _final_census_age_comparisons(census_pop, final, census_emp, census_licenses,
                                  final_trips, out, manifest):
    """Like-for-like FINAL vs Census age rates; travel has no census rate.

    Residence-independent metropolitan totals include exported households with
    no home activity, while city reports receive only mapped city residents.
    Census age-bin splitting follows the existing explicit uniform assumption.
    """
    if final is None:
        return
    for metric, reference, breaks, label, slug in (
        ("employed_n", census_emp, EMPLOYMENT_BREAKS, "Employed residents", "employment"),
        ("license_n", census_licenses, LICENSE_BREAKS, "Driving-licence holders", "driving_licence"),
    ):
        rows=[]
        for sex_group in (None, "male", "female"):
            by_sex = sex_group is not None
            c=census_outcome_rates(census_pop,reference,breaks,by_sex=by_sex)
            f=rate_groups(final,breaks,metric,group_sex=by_sex)
            if by_sex:
                c=c.loc[c.sex.eq(sex_group)]
                f=f.loc[f.sex.eq(sex_group)]
            c=c.set_index("age_start")
            f=f.set_index("age_start")
            table=pd.DataFrame(index=sorted(set(c.index).union(f.index)))
            table.index.name="age_start"
            table["census_pct"]=c.rate_pct
            table["final_pct"]=f.rate_pct
            table["census_total_residents"]=c.weighted_total
            table["final_total_residents_expanded"]=f.weighted_total
            table["census_with_attribute"]=c.weighted_yes
            table["final_with_attribute_expanded"]=f.weighted_yes
            table["gap_percentage_points"]=table.final_pct-table.census_pct
            table["sex"]=sex_group or "all"
            rows.append(table.reset_index())
            if table[["census_pct","final_pct"]].dropna(how="all").empty:
                continue
            x=np.arange(len(table))
            fig,ax=plt.subplots(figsize=(max(10,len(x)*.62),5.4))
            ax.bar(x-.21,table.census_pct,width=.42,color=COLORS["Census"],label="Census")
            ax.bar(x+.21,table.final_pct,width=.42,color=COLORS["Final"],label="Final")
            labels=[_age_bin_label(i,breaks) for i in table.index]
            ax.set_xticks(x,labels,rotation=45,ha="right")
            ax.set(ylabel="Share of residents in age group (%)",ylim=(0,100),
                   title=label+" by age · Final vs Census"+(" · "+sex_group if by_sex else ""))
            ax.grid(axis="y",alpha=.2);ax.set_axisbelow(True);ax.legend(frameon=False)
            name=f"final_census_{slug}_by_age"+("_"+sex_group if by_sex else "")
            _save(fig,out,manifest,name,label+" — Final vs Census by age"+
                  (" — "+sex_group if by_sex else ""),
                  "Both percentages divide by all residents in the age group; census employment/licence numerators are section-level estimates.")
        pd.concat(rows,ignore_index=True).to_csv(out/f"final_census_{slug}_by_age.csv",index=False)

    # Residents by age are directly comparable between the two populations.
    c=census_population_in_bins(census_pop,AGE_BREAKS,by_sex=False).set_index("age_start")
    f=final.copy()
    f["age_start"]=pd.cut(f.age,AGE_BREAKS,labels=AGE_BREAKS[:-1],right=False).astype(float)
    fw=f.groupby("age_start",observed=True)._w.sum()
    age=pd.DataFrame(index=sorted(set(c.index).union(fw.index)))
    age.index.name="age_start"
    age["census_residents"]=c.population
    age["final_residents_expanded"]=fw
    age["census_pct"]=100*age.census_residents/age.census_residents.sum()
    age["final_pct"]=100*age.final_residents_expanded/age.final_residents_expanded.sum()
    age["gap_percentage_points"]=age.final_pct-age.census_pct
    age.to_csv(out/"final_census_population_age_distribution.csv")
    x=np.arange(len(age))
    fig,ax=plt.subplots(figsize=(max(10,len(x)*.62),5.1))
    ax.bar(x-.21,age.census_pct,width=.42,label="Census",color=COLORS["Census"])
    ax.bar(x+.21,age.final_pct,width=.42,label="Final",color=COLORS["Final"])
    ax.set_xticks(x,[_age_bin_label(i,AGE_BREAKS) for i in age.index],rotation=45,ha="right")
    ax.set(ylabel="Share of total residents (%)",title="Population age distribution · Final vs Census")
    ax.legend(frameon=False);ax.grid(axis="y",alpha=.2)
    _save(fig,out,manifest,"final_census_population_by_age","Population age distribution · Final vs Census")

    # Sex composition by age is an additional DIRECT Census comparison.
    sex_c=census_population_in_bins(census_pop,AGE_BREAKS,by_sex=True)
    sex_c=sex_c.pivot(index="age_start",columns="sex",values="population")
    sex_f=final.loc[final.sex_norm.isin(["male","female"])].copy()
    sex_f["age_start"]=pd.cut(sex_f.age,AGE_BREAKS,labels=AGE_BREAKS[:-1],right=False).astype(float)
    sex_f=sex_f.groupby(["age_start","sex_norm"],observed=True)._w.sum().unstack()
    age_sex=pd.DataFrame(index=sorted(set(sex_c.index).union(sex_f.index)))
    age_sex.index.name="age_start"
    age_sex["census_female_pct"]=100*sex_c.get("female",pd.Series(dtype=float))/sex_c.sum(axis=1).replace(0,np.nan)
    age_sex["final_female_pct"]=100*sex_f.get("female",pd.Series(dtype=float))/sex_f.sum(axis=1).replace(0,np.nan)
    age_sex["gap_percentage_points"]=age_sex.final_female_pct-age_sex.census_female_pct
    age_sex.to_csv(out/"final_census_female_share_by_age.csv")
    x=np.arange(len(age_sex))
    fig,ax=plt.subplots(figsize=(max(10,len(x)*.62),5.1))
    ax.bar(x-.21,age_sex.census_female_pct,width=.42,label="Census",color=COLORS["Census"])
    ax.bar(x+.21,age_sex.final_female_pct,width=.42,label="Final",color=COLORS["Final"])
    ax.set_xticks(x,[_age_bin_label(i,AGE_BREAKS) for i in age_sex.index],rotation=45,ha="right")
    ax.set(ylabel="Female residents / residents in age group (%)",ylim=(0,100),
           title="Female share by age · Final vs Census")
    ax.legend(frameon=False);ax.grid(axis="y",alpha=.2)
    _save(fig,out,manifest,"final_census_female_share_by_age","Female share by age · Final vs Census")

    # The census has no number of education trips nor a census student-enrolment
    # field. Show a FINAL-only trip-participation rate together with the actual
    # Census-vs-Final age-group population counts, never a fabricated census rate.
    if final_trips is not None:
        if not {"person_id","following_purpose"}.issubset(final_trips):
            raise ValueError("Final trips need person_id and following_purpose for education diagnostics")
        edu_ids=set(final_trips.loc[final_trips.following_purpose.astype("string").str.strip().str.lower().eq("education"),
                                    "person_id"].dropna())
        students=final.copy()
        students["education_trip_n"]=students.person_id.isin(edu_ids).astype(float)
        rate=rate_groups(students,AGE_BREAKS,"education_trip_n").set_index("age_start")
        joined=age.join(rate[["weighted_yes","weighted_total","rate_pct"]].rename(columns={
            "weighted_yes":"final_education_trip_participants_expanded",
            "weighted_total":"final_age_group_residents_expanded",
            "rate_pct":"final_education_trip_participation_pct"}),how="left")
        joined.to_csv(out/"final_education_trip_participation_by_age_census_context.csv")
        fig,(ax,bx)=plt.subplots(2,1,figsize=(max(10,len(joined)*.62),8.0),sharex=True,
                                 gridspec_kw={"height_ratios":[1,1.15]})
        x=np.arange(len(joined))
        ax.bar(x,joined.final_education_trip_participation_pct,color=COLORS["Final"],width=.62,
               label="Final: ≥1 trip to education")
        ax.set(ylabel="Final participants / age group (%)",ylim=(0,100),
               title="Education trip participation by age · Final population")
        ax.grid(axis="y",alpha=.2);ax.legend(frameon=False)
        bx.bar(x-.21,joined.census_residents,width=.42,label="Census residents",color=COLORS["Census"])
        bx.bar(x+.21,joined.final_residents_expanded,width=.42,label="Final residents",color=COLORS["Final"])
        bx.set(ylabel="Residents (expanded)",xlabel="Age groups")
        bx.set_xticks(x,[_age_bin_label(i,AGE_BREAKS) for i in joined.index],rotation=45,ha="right")
        bx.grid(axis="y",alpha=.2);bx.legend(frameon=False)
        _save(fig,out,manifest,"final_education_trips_by_age_census_context",
              "Education-trip participation (Final) with Census population context",
              "The Census source has no observed education-trip participation. Top: Final-only share of each age group with a modeled education trip; bottom: Census vs Final population counts by age.")


def _age_bin_label(start,breaks):
    i=next(i for i,v in enumerate(breaks[:-1]) if float(v)==float(start))
    end=breaks[i+1]
    return f"{int(start)}+" if np.isinf(end) else f"{int(start)}–{int(end)-1}"


def _work_trip_table(persons, trips, source, breaks, min_eff):
    if trips is None or trips.empty:
        return pd.DataFrame(), pd.DataFrame()
    if not {"person_id","following_purpose"}.issubset(trips):
        raise ValueError(f"{source}: trips missing person_id/following_purpose")
    if trips.person_id.isna().any():
        raise ValueError(f"{source}: trip with null person ID")
    t = trips.copy()
    purpose = t.following_purpose.astype("string").str.strip().str.lower()
    work_counts = t.loc[purpose.eq("work")].groupby("person_id").size()
    education_counts = t.loc[purpose.eq("education")].groupby("person_id").size()
    from_work = t.loc[t.get("preceding_purpose",pd.Series(index=t.index,dtype="string")).astype("string").str.lower().eq("work")].groupby("person_id").size()
    p = persons.copy()
    p["work_dest_trips"] = p.person_id.map(work_counts).fillna(0)
    p["work_origin_trips"] = p.person_id.map(from_work).fillna(0)
    p["edu_dest_trips"] = p.person_id.map(education_counts).fillna(0)
    p["work_trip_participation"] = p.work_dest_trips.gt(0).astype(float)
    p["education_trip_participation"] = p.edu_dest_trips.gt(0).astype(float)
    p["any_trip_participation"] = p.person_id.isin(t.person_id).astype(float)
    rates=[]
    for outcome in ("work_trip_participation","education_trip_participation","any_trip_participation"):
        for split in (False,True):
            result=rate_groups(p, breaks, outcome, group_sex=split)
            result["metric"]=outcome;result["by_sex"]=split;result["source"]=source
            rates.append(result)
    table=pd.concat(rates,ignore_index=True)
    rows=[]
    p["age_start"]=pd.cut(p.age,breaks,labels=breaks[:-1],right=False).astype(float)
    for age,group in p.groupby("age_start", observed=True):
        for k in ("work_dest_trips", "work_origin_trips", "edu_dest_trips"):
            rows.append({"source":source,"age_start":age,"metric":k,
                         "weighted_mean_per_person":np.average(group[k],weights=group._w),
                         "weighted_total":np.dot(group[k],group._w),
                         "effective_n":group._w.sum()**2 / np.square(group._w).sum()})
    return table,pd.DataFrame(rows)


def _work_travel(syn_sources, hts_reweighted, syn_trips, out, manifest, min_eff):
    data={}
    for k,v in syn_sources.items():
        if k=="Final" and syn_trips is not None:
            data[k]=(v,syn_trips)
    if hts_reweighted is not None:
        _, htp, htt = hts_reweighted
        data["HTS"]=(prepare_persons(htp,"HTS Kish",weight_col="person_weight"),htt)
    rates,means=[],[]
    for k,(p,t) in data.items():
        r,m=_work_trip_table(p,t,k,TRAVEL_BREAKS,min_eff)
        if len(r):rates.append(r)
        if len(m):means.append(m)
    if not rates:
        return
    rates=pd.concat(rates,ignore_index=True)
    means=pd.concat(means,ignore_index=True) if means else pd.DataFrame()
    rates["masked_for_plot"]=rates.source.eq("HTS") & rates.n_eff.lt(min_eff)
    rates.to_csv(out/"travel_participation_by_age_sex.csv",index=False)
    means.to_csv(out/"travel_legs_per_person_by_age.csv",index=False)
    for metric,title in (("work_trip_participation","People with ≥1 trip to work"),
                         ("education_trip_participation","People with ≥1 trip to education"),
                         ("any_trip_participation","People with ≥1 trip")):
        r=rates.loc[rates.metric.eq(metric) & ~rates.by_sex]
        _age_group_bars(r,out,manifest,"travel_"+metric,title+" by age (CITY only)",min_eff)
    if not means.empty:
        for metric in ("work_dest_trips","work_origin_trips","edu_dest_trips"):
            m=means.loc[means.metric.eq(metric)].rename(columns={"weighted_mean_per_person":"rate_pct"})
            _age_group_bars(m,out,manifest,"travel_"+metric,"Mean "+metric.replace("_"," ")+" by age (CITY)",min_eff,
                        ylabel="Mean trip legs / person")
    # Trip-purpose and mode shares: sample one trip LEG, weighted by Kish person
    # factor. The counts are not unique home/work persons or commute OD totals.
    mode_rows=[]
    for name,(p,t) in data.items():
        work=t.loc[t.following_purpose.astype("string").str.lower().eq("work")].copy()
        if "mode" not in work:continue
        w=p[["person_id","_w"]]
        work=work.merge(w,on="person_id",how="inner",validate="many_to_one")
        s=work.groupby("mode",observed=True)._w.sum()
        for mode,v in s.items():
            mode_rows.append({"source":name,"mode":str(mode),"weighted_legs":float(v),
                              "share_pct":float(100*v/s.sum()) if s.sum() else np.nan})
    if mode_rows:
        m=pd.DataFrame(mode_rows);m.to_csv(out/"work_destination_mode_shares.csv",index=False)
        _bars({name:g.set_index("mode").weighted_legs for name,g in m.groupby("source")},
              "Share of trips ending at work (%)",out,manifest,"travel_work_modes",
              "Mode distribution of trips ending at work — city only")
    # Age-specific modes and crow-fly commuting distances, using the same
    # work-destination trip-leg definition on HTS and synthetic export.
    mode_age=[];distance_age=[]
    for name,(p,t) in data.items():
        if "following_purpose" not in t:continue
        work=t.loc[t.following_purpose.astype("string").str.lower().eq("work")].copy()
        work=work.merge(p[["person_id","age","_w"]],on="person_id",how="inner",validate="many_to_one",suffixes=("","_person"))
        age=work["age_person"] if "age_person" in work else work.age
        work["age_start"]=pd.cut(age,TRAVEL_BREAKS,labels=TRAVEL_BREAKS[:-1],right=False).astype(float)
        if "mode" in work:
            for (group_age,mode),grp in work.dropna(subset=["age_start","mode"]).groupby(["age_start","mode"],observed=True):
                mode_age.append({"source":name,"age_start":group_age,"mode":str(mode),"weighted_legs":grp._w.sum()})
        if "euclidean_distance" in work:
            dist=numeric(work.euclidean_distance)/1000
            d=work.assign(distance_km=dist)
            d=d.loc[d.distance_km.between(0.01,100) & d.age_start.notna() & d._w.gt(0)]
            for group_age,grp in d.groupby("age_start",observed=True):
                distance_age.append({"source":name,"age_start":group_age,"weighted_legs":grp._w.sum(),
                                     "mean_crowfly_km":np.average(grp.distance_km,weights=grp._w)})
    if mode_age:
        a=pd.DataFrame(mode_age)
        a["share_pct"] = 100*a.weighted_legs/a.groupby(["source","age_start"]).weighted_legs.transform("sum")
        a.to_csv(out/"work_mode_share_by_age.csv",index=False)
        for name,group in a.groupby("source"):
            pivot=group.pivot_table(index="mode",columns="age_start",values="share_pct",fill_value=0,observed=True)
            if pivot.empty:continue
            fig,ax=plt.subplots(figsize=(max(8,.75*len(pivot.columns)),max(4,.43*len(pivot))))
            im=ax.imshow(pivot.to_numpy(),vmin=0,vmax=100,aspect="auto",cmap="YlGnBu")
            ax.set_xticks(range(len(pivot.columns)),[str(int(x)) for x in pivot.columns],rotation=45)
            ax.set_yticks(range(len(pivot.index)),pivot.index)
            ax.set(xlabel="Age group",title="Modes of trips ending at work · "+name+" (city)")
            fig.colorbar(im,ax=ax,label="Share of work-destination legs (%)")
            _save(fig,out,manifest,"travel_work_modes_age_"+name.lower(),
                  "Work-destination mode share by age · "+name)
    if distance_age:
        d=pd.DataFrame(distance_age)
        d.to_csv(out/"work_crowfly_distance_by_age.csv",index=False)
        fig,ax=plt.subplots(figsize=(10,5.3))
        for name,g in d.groupby("source"):
            ax.plot(g.age_start,g.mean_crowfly_km,marker="o",lw=2,label=name,color=COLORS.get(name,"#888"))
        ax.set(title="Mean distance of trips ending at work by age — city",xlabel="Age (group start)",ylabel="Mean crow-fly distance (km)")
        ax.grid(axis="y",alpha=.2);ax.legend(frameon=False)
        _save(fig,out,manifest,"travel_work_crowfly_distance_age",
              "Mean work-destination trip distance by age (crow fly)",
              "Both datasets use euclidean_distance; distances >100 km and zeros are excluded.")


def create_diagnostics(ipu, final, census_population, census_households, census_employment,
                       census_licenses, hts_filtered, hts_reweighted, final_trips,
                       output_dir, sampling_rate=1., min_effective_n=30, city_code="41091",
                       final_homes=None, zones=None):
    out=Path(output_dir);out.mkdir(parents=True,exist_ok=True)
    if final is not None:
        if zones is None and final_homes is not None:
            raise ValueError("Provide OD polygons along with exported homes")
        final,home_qa=assign_final_residences(final,final_homes,
                     _validate_zones(zones) if zones is not None else None,city_code)
        final=prepare_persons(final,"Final",sampling_rate)
        write_json(out/"final_home_mapping_quality.json",home_qa)
    else: final=None
    if final is None: raise ValueError("Final exported population required for Final-vs-Census validation")
    data={"Final":final}
    manifest=[];qa=[]
    source_summary({"Final":final}).to_csv(out/"missingness_and_source_coverage.csv",index=False)
    if final is not None and final_trips is not None:
        citymask=final.municipality_id_validation.eq(city_code)
        final_city=final.loc[citymask].copy()
        # Restrict Final-trip calculations to geocoded residents of the city.
        trips_city=final_trips.loc[final_trips.person_id.isin(final_city.person_id)].copy()
    else:
        final_city=None;trips_city=None
    for scope in ("metropolitan", "seville_city"):
        f=out/scope;f.mkdir(exist_ok=True)
        cp=census_population.copy();ch=census_households.copy()
        ce=census_employment.copy();cl=census_licenses.copy()
        p={name:src.copy() for name,src in data.items()}
        if scope=="seville_city":
            for name in p:
                p[name]=p[name].loc[p[name].municipality_id_validation.eq(city_code)]
            for df in (cp,ch,ce,cl):
                if "municipality_id" not in df:
                    raise ValueError("Census reference missing municipality_id")
                df.drop(df.index[~ids(df.municipality_id).eq(city_code).fillna(False)],inplace=True)
        if cp.empty:
            raise ValueError(f"No census population for {scope}")
        plots=[]
        _age_mix(cp,p,f,plots)
        _households(ch,p,None,f,plots)
        _whole_population_rates(cp,ce,cl,p,f,plots)
        # Preserve prior machine-readable age table, now limited to Final and Census.
        age_sources={"Final":p["Final"]} if "Final" in p else {}
        for metric,ref,breaks,title in (
            ("employed_n",ce,EMPLOYMENT_BREAKS,"Employment rate by age"),
            ("license_n",cl,LICENSE_BREAKS,"Driving licence by age"),
        ):
            _rate_metric(cp,ref,age_sources,metric,breaks,0,f,plots,
                         {"employed_n":"03_employment","license_n":"04_license"}[metric],
                         title+" · "+scope.replace("_"," "),min_effective_n)
        relevant_trips=(trips_city if scope=="seville_city" else final_trips)
        if "Final" in p:
            _final_census_age_comparisons(cp,p["Final"],ce,cl,relevant_trips,f,plots)
        write_index(f, "Seville population diagnostics — "+scope,plots,[
            "Census 2022 is the reference for population, employment, household sizes/totals and driving licences.",
            "Employment census is model-disaggregated to sections and age classes; licence census is adjusted from 2024 to 2022.",
            "Census age-bin denominators are uniformly distributed within source five-year bins when exact bins differ.",
            "Only Final and Census are compared. Education-trip participation remains a Final-only behavior indicator.",
            "The census contains no education-trip participation; education-by-age displays Final trip percentages with Census population counts only, NOT a Census participation rate.",
            "Final trips ending at work, trips originating at work, and home–work person OD are different quantities.",
            "Employment/licence all-resident shares use the WHOLE population, including children; age-specific rates use each age bin.",
            "City-only final figures omit exported households without home locations; metropolitan non-spatial totals keep them. See the root exclusion report.",
            "No IPU or HTS data are loaded for this validation stage.",
        ])
        pd.DataFrame(plots).to_csv(f/"plot_manifest.csv",index=False)
        manifest.extend([{**x,"scope":scope} for x in plots])
        qa.append({"scope":scope,"census_population":float(numeric(cp.weight).sum()),
                   "final_expanded":float(p["Final"]._w.sum()) if "Final" in p else np.nan,
                   "census_households":float(numeric(ch.total_households).sum()),
                   "census_employed_residents":float(numeric(ce.weight).sum()),
                   "census_driving_licences":float(numeric(cl.weight).sum())})
    if final is not None:
        # Metropolitan totals need no home; city-scoped figures do.
        affected=[m for m in manifest if m["scope"] == "seville_city"
                  and not m["file"].endswith("_gap_heatmap.png")]
        if not home_qa.get("households_missing_home",0):
            affected=[]
        write_home_exclusion_report(out,home_qa,affected,
                                    report_name="Seville population validation")
    pd.DataFrame(qa).to_csv(out/"benchmark_summary.csv",index=False)
    pd.DataFrame(manifest).to_csv(out/"plot_manifest.csv",index=False)
    write_json(out/"validation_metadata.json",{
        "census_reference_year":2022,"sampling_rate":sampling_rate,
        "minimum_hts_effective_n":None,
        "city_municipality_code":city_code,
        "census_sources":["population","households (2021 adjusted to 2022)",
                          "employment extrapolated by age and sex","driving licences 2024 adjusted to 2022"],
        "benchmark_scope":"Final vs Census only; no IPU or HTS validation comparisons",
        "work_trips":"Final-only trip statistics, not comparable to Census commuting trips",
        "diagnostics_are_validation_not_calibration":True,
        "age_specific_comparison":"Final vs Census only; education-trip participation has Final rates and Census population context only",
        "employment_licence_overall_denominator":"all residents, including children",
        "missing_home_policy":"Exclude only from home-location-dependent validation, not from non-spatial population/household totals",
    })
    root_figures=([{"file":"home_location_exclusions.png",
                   "title":"Households excluded from home-location-dependent validation",
                   "note":"See home_location_affected_plots.csv for affected city-only figures."}]
                  if final is not None else [])
    write_index(out,"Seville population validation",root_figures,[
        "Two reports: metropolitan (Census vs Final) and city (Census vs Final).",
        "Age-specific Final-vs-Census comparisons are grouped bars. Final education trips are descriptive, without invented Census participation rates.",
        "See home_location_exclusions.png for the count without exported homes and home_location_affected_plots.csv for affected figures.",
    ])
    report=out/"index.html"
    report.write_text(report.read_text().replace("</body>",
        '<p><a href="home_location_exclusions.png">Home-location exclusion chart</a> — '
        '<a href="home_location_affected_plots.csv">affected figures</a></p>'
        '<p><a href="metropolitan/index.html">Metropolitan census validation</a></p>'
        '<p><a href="seville_city/index.html">Seville municipality census validation</a></p></body>'),encoding="utf-8")
    return pd.DataFrame(qa)


